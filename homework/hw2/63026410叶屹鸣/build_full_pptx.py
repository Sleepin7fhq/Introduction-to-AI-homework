def section_slide(prs, num, title, sub):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    band = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(13.333), Inches(2.15))
    band.fill.solid(); band.fill.fore_color.rgb = NAVY
    band.line.fill.background(); band.shadow.inherit = False
    tb = s.shapes.add_textbox(Inches(0.75), Inches(0.42), Inches(11.8), Inches(0.5))
    p = tb.text_frame.paragraphs[0]
    r = p.add_run(); r.text = num
    set_run(r, 15, True, RGBColor(0xFF, 0xC0, 0x00), base.CN)
    add_text(s, 0.75, 0.90, 11.8, 1.1, [(title, "h")], base_size=32)
    add_text(s, 0.78, 1.72, 11.8, 0.4, [(sub, "s")], base_size=12)
    return s


